import json
from typing import Optional
from uuid import UUID

from app.database.repository import BaseRepository
from app.enums.dataset_status import DatasetStatus
from app.models.dataset_schema_table import ColumnSchema
from app.models.dataset_table import DatasetTable


class DatasetRepository(BaseRepository[DatasetTable]):
    """Repository for dataset metadata and inferred schemas.

    Reads dataset rows, updates preparation status and counters, and upserts the
    inferred column schema generated by the workflow.
    """

    async def get_by_id(self, dataset_id: UUID) -> Optional[DatasetTable]:
        async with self.pool.acquire() as connection:
            row = await connection.fetchrow(
                """
                SELECT
                    id,
                    name,
                    status,
                    raw_object_key,
                    prepared_object_key,
                    rows_count,
                    columns_count,
                    error_message,
                    created_at,
                    updated_at
                FROM datasets
                WHERE id = $1
                """,
                dataset_id,
            )

        if row is None:
            return None

        return DatasetTable(
            id=row["id"],
            name=row["name"],
            status=DatasetStatus(row["status"]),
            raw_object_key=row["raw_object_key"],
            prepared_object_key=row["prepared_object_key"],
            rows_count=row["rows_count"],
            columns_count=row["columns_count"],
            error_message=row["error_message"],
            created_at=row["created_at"],
            updated_at=row["updated_at"],
        )

    async def update_status(
        self,
        dataset_id: UUID,
        status: DatasetStatus,
        error_message: Optional[str] = None,
    ) -> bool:
        async with self.pool.acquire() as connection:
            result = await connection.execute(
                """
                UPDATE datasets
                SET
                    status = $2,
                    error_message = $3,
                    updated_at = NOW()
                WHERE id = $1
                """,
                dataset_id,
                status.value,
                error_message,
            )

        return result == "UPDATE 1"

    async def update_prepared_info(
        self,
        dataset_id: UUID,
        prepared_object_key: str,
        rows_count: int,
        columns_count: int,
    ) -> Optional[DatasetTable]:
        async with self.pool.acquire() as connection:
            row = await connection.fetchrow(
                """
                UPDATE datasets
                SET
                    status = $2,
                    prepared_object_key = $3,
                    rows_count = $4,
                    columns_count = $5,
                    error_message = NULL,
                    updated_at = NOW()
                WHERE id = $1
                RETURNING
                    id,
                    name,
                    status,
                    raw_object_key,
                    prepared_object_key,
                    rows_count,
                    columns_count,
                    error_message,
                    created_at,
                    updated_at
                """,
                dataset_id,
                DatasetStatus.PREPARED.value,
                prepared_object_key,
                rows_count,
                columns_count,
            )

        if row is None:
            return None

        return DatasetTable(
            id=row["id"],
            name=row["name"],
            status=DatasetStatus(row["status"]),
            raw_object_key=row["raw_object_key"],
            prepared_object_key=row["prepared_object_key"],
            rows_count=row["rows_count"],
            columns_count=row["columns_count"],
            error_message=row["error_message"],
            created_at=row["created_at"],
            updated_at=row["updated_at"],
        )

    async def save_schema(
        self,
        dataset_id: UUID,
        schema_data: list[ColumnSchema],
    ) -> bool:
        schema_json = json.dumps(
            [column.model_dump(mode="json") for column in schema_data]
        )

        async with self.pool.acquire() as connection:
            await connection.execute(
                """
                INSERT INTO dataset_schemas (dataset_id, columns, created_at, updated_at)
                VALUES ($1, $2, NOW(), NOW())
                ON CONFLICT (dataset_id)
                DO UPDATE SET
                    columns = EXCLUDED.columns,
                    updated_at = NOW()
                """,
                dataset_id,
                schema_json,
            )

        return True

    async def get_schema(self, dataset_id: UUID) -> Optional[list[ColumnSchema]]:
        async with self.pool.acquire() as connection:
            row = await connection.fetchrow(
                """
                SELECT columns
                FROM dataset_schemas
                WHERE dataset_id = $1
                """,
                dataset_id,
            )

        if row is None:
            return None

        columns = row["columns"]

        if isinstance(columns, str):
            columns = json.loads(columns)

        return [ColumnSchema(**column) for column in columns]
