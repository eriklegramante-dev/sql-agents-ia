from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, field_validator

from app.chat.models import ArtifactContent, MetadataValue


class ChatMessageRequestDTO(BaseModel):
    """
    Represents an incoming chat message request.

    Attributes:
        user_id:
            Identifier of the user sending the message.

        message:
            Message submitted by the user.

        dataset_id:
            Optional dataset identifier used for analytical requests.

        session_id:
            Optional chat session identifier.

        metadata:
            Optional contextual metadata associated with the message.
    """

    model_config = ConfigDict(extra="forbid")

    user_id: int | str = Field(
        ...,
        description="Identifier of the user sending the message.",
    )
    message: str = Field(
        ...,
        min_length=1,
        description="Message submitted by the user.",
    )
    dataset_id: UUID | None = Field(
        default=None,
        description="Optional dataset identifier used for analytical requests.",
    )
    session_id: str | None = Field(
        default=None,
        description="Optional chat session identifier.",
    )
    metadata: dict[str, MetadataValue] | None = Field(
        default=None,
        description="Optional contextual metadata associated with the message.",
    )

    @field_validator("user_id")
    @classmethod
    def validate_user_id(cls, value: int | str) -> int | str:
        """
        Validates and normalizes the user identifier.

        Args:
            value:
                User identifier received in the request payload.

        Returns:
            int | str:
                Normalized user identifier after validation.

        Raises:
            ValueError:
                If the user identifier is empty or otherwise invalid.
        """
        if isinstance(value, int):
            if value <= 0:
                raise ValueError("User ID must be greater than zero.")

            return value

        normalized_value = value.strip()

        if not normalized_value:
            raise ValueError("User ID must not be empty.")

        return normalized_value

    @field_validator("message")
    @classmethod
    def normalize_message(cls, value: str) -> str:
        """
        Validates and normalizes the user message.

        Args:
            value:
                Message received in the request payload.

        Returns:
            str:
                Normalized message with surrounding whitespace removed.

        Raises:
            ValueError:
                If the message is empty after normalization.
        """
        normalized_value = value.strip()

        if not normalized_value:
            raise ValueError("Message must not be empty.")

        return normalized_value

    @field_validator("session_id")
    @classmethod
    def normalize_session_id(cls, value: str | None) -> str | None:
        """
        Validates the optional session identifier.

        Args:
            value:
                Session identifier received in the request payload.

        Returns:
            str | None:
                Normalized session identifier or None when omitted.

        Raises:
            ValueError:
                If the session identifier is provided but is empty after
                normalization.
        """
        if value is None:
            return None

        normalized_value = value.strip()

        if not normalized_value:
            return None

        return normalized_value


class ChatArtifactDTO(BaseModel):
    """
    Represents an optional artifact generated by an analysis tool.

    Attributes:
        type:
            Artifact type, such as table or chart.

        content:
            Structured artifact content returned by the analysis tool.
    """

    model_config = ConfigDict(extra="forbid")

    type: str = Field(
        ...,
        min_length=1,
        description="Artifact type, such as table or chart.",
    )
    content: ArtifactContent = Field(
        ...,
        description="Structured artifact content returned by the analysis tool.",
    )


class ChatMessageResponseDataDTO(BaseModel):
    """
    Represents the processed chat message response data.

    Attributes:
        user_id:
            Identifier of the user associated with the processed message.

        session_id:
            Chat session identifier associated with the response, when
            available.

        answer:
            Generated assistant answer.

        intent:
            Detected intent used to process the message.

        tool_used:
            Name of the tool used during processing, when one is selected.

        dataset_id:
            Dataset identifier associated with the request, when available.

        artifact:
            Optional artifact produced during chat processing.
    """

    model_config = ConfigDict(extra="forbid")

    user_id: int | str
    session_id: str | None
    answer: str
    intent: str
    tool_used: str | None
    dataset_id: UUID | None
    artifact: ChatArtifactDTO | None = None


class ChatMessageResponseDTO(BaseModel):
    """
    Represents the standard response envelope for chat messages.

    Attributes:
        success:
            Indicates whether chat message processing succeeded.

        message:
            Human-readable response message.

        data:
            Processed chat message payload returned on success.

        errors:
            Error details returned when processing fails.
    """

    model_config = ConfigDict(extra="forbid")

    success: bool
    message: str
    data: ChatMessageResponseDataDTO | None = None
    errors: list[str] | None = None
