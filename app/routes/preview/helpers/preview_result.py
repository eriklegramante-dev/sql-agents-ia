from dataclasses import dataclass
from typing import Any


@dataclass(slots=True)
class PreviewResult:
    """
    Represents the dataset preview generated by the preview reader.

    This model encapsulates the extracted columns, serialized preview rows,
    and total dataset row count before the response is assembled by the
    workflow.

    Attributes:
        columns:
            Dataset column names.
        rows:
            Serialized preview rows.
        rows_count:
            Total number of rows available in the dataset.
    """

    columns: list[str]
    rows: list[dict[str, Any]]
    rows_count: int
