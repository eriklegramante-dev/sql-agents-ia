from dataclasses import dataclass


@dataclass
class ChartPlan:
    """
    Structured analytical chart execution plan.

    Holds the inferred SQL query, resolved chart visualization type, axis
    field mappings, and descriptive title generated by the chart planner tool.

    Attributes:
        sql:
            Read-only analytical SQL query generated for the dataset.
        chart_type:
            Resolved visual chart representation (e.g., bar, line, pie).
        x_field:
            Column name mapped to the horizontal axis or category dimension.
        y_field:
            Column name mapped to the vertical axis or metric dimension.
        title:
            Descriptive title for the resulting chart visualization.
    """

    sql: str
    chart_type: str
    x_field: str
    y_field: str
    title: str


class ChartPlannerTool:
    """
    Planning tool responsible for translating natural-language queries into charts.

    Analyzes natural-language requests against the dataset table structure and
    generates a structured execution plan containing a safe analytical SQL query,
    appropriate visualization format, and axis field mappings.
    """

    def plan_chart(
        self,
        question: str,
        table_name: str,
        schema_columns: list[str],
    ) -> ChartPlan:
        """
        Plans a chart execution strategy based on a natural-language question.

        Applies heuristic rules against the input question and available schema
        columns to infer the visual format, select axes dimensions, and generate
        the aggregated analytical SELECT statement.

        Args:
            question:
                Natural-language query or chart request provided by the user.
            table_name:
                Target dataset table or view identifier in the analytical engine.
            schema_columns:
                List of accessible column names within the dataset schema.

        Returns:
            ChartPlan:
                Inferred plan containing the SQL query, chart format, and field mappings.
        """
        q_lower = question.lower()
        x_col = schema_columns[0] if schema_columns else "id"
        y_col = schema_columns[1] if len(schema_columns) > 1 else schema_columns[0]

        if "line" in q_lower or "over time" in q_lower:
            chart_type = "line"
        elif "pie" in q_lower or "share" in q_lower:
            chart_type = "pie"
        else:
            chart_type = "bar"

        sql = (
            f"SELECT {x_col}, COUNT({y_col}) AS total "
            f"FROM {table_name} "
            f"GROUP BY {x_col} "
            f"ORDER BY total DESC"
        )

        return ChartPlan(
            sql=sql,
            chart_type=chart_type,
            x_field=x_col,
            y_field="total",
            title=f"Chart for: {question}",
        )