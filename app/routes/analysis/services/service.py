from app.core.analysis.workflow import AnalysisQueryWorkflow
from app.logs.setup_logger import LOGGER, LoggerManager
from app.routes.analysis.dtos.dto import (
    AnalysisQueryRequestDTO,
    AnalysisQueryResponseDataDTO,
)


class AnalysisQueryService:
    """
    Coordinates dataset analysis query execution at the service layer.

    This service receives the validated analysis request, delegates the
    business execution to the analysis workflow, and returns the structured
    response data generated by the workflow.

    The service contains no dataset validation, SQL safety rules, storage
    access, or DuckDB execution logic. Those responsibilities remain isolated
    inside the workflow and its injected collaborators.

    Dependencies are received through constructor injection, preventing the
    service from instantiating concrete workflow or logging implementations.

    Args:
        workflow:
            Workflow responsible for executing the complete dataset analysis
            query flow.

        logger:
            Logger manager used to record service execution events.

    Attributes:
        workflow:
            Workflow responsible for coordinating analytical query execution.

        logger:
            Logger manager used during service execution.
    """

    def __init__(
        self,
        workflow: AnalysisQueryWorkflow,
        logger: LoggerManager | None = None,
    ) -> None:
        self.workflow = workflow
        self.logger = logger or LOGGER

    async def execute(
        self,
        request: AnalysisQueryRequestDTO,
    ) -> AnalysisQueryResponseDataDTO:
        """
        Execute the dataset analysis query service.

        Args:
            request:
                Validated analysis query request received from the controller.

        Returns:
            AnalysisQueryResponseDataDTO:
                Structured analytical result produced by the workflow.
        """
        self.logger.log_info(
            f"Executing analysis query service for dataset "
            f"{request.dataset_id}."
        )

        response_data = await self.workflow.execute(request)

        self.logger.log_info(
            f"Analysis query service completed for dataset "
            f"{request.dataset_id}."
        )

        return response_data