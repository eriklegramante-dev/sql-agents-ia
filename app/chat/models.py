from dataclasses import dataclass
from enum import Enum
from typing import Any
from uuid import UUID


class ChatIntent(str, Enum):
    """
    Supported intents handled by the chat workflow.

    Attributes:
        GENERAL_CHAT:
            Intent used for conversational messages that do not require a
            dataset operation.

        DATASET_QUESTION:
            Intent used for analytical questions about a dataset.

        CHART_REQUEST:
            Intent used when the user asks for chart generation.

        UNSUPPORTED:
            Intent used when the message cannot be processed by the chat
            workflow.
    """

    GENERAL_CHAT = "general_chat"
    DATASET_QUESTION = "dataset_question"
    CHART_REQUEST = "chart_request"
    UNSUPPORTED = "unsupported"


@dataclass
class ChatPreferences:
    """
    Represents the effective user preferences used by the chat workflow.

    Attributes:
        persona_name:
            Name of the assistant persona applied to the response.

        persona_description:
            Description of the assistant persona applied to the response.

        response_style:
            Preferred style used when generating the assistant response.

        language:
            Preferred response language.

        tool_preferences:
            Ordered tool preferences available to the chat workflow.

        guardrails:
            Behavioral guardrails applied while processing the message.
    """

    persona_name: str
    persona_description: str
    response_style: str
    language: str
    tool_preferences: tuple[str, ...]
    guardrails: tuple[str, ...]


@dataclass
class ChatMessageInput:
    """
    Represents the validated input consumed by the chat workflow.

    Attributes:
        user_id:
            Identifier of the user sending the message.

        message:
            Validated message submitted by the user.

        dataset_id:
            Optional dataset identifier used for analytical requests.

        session_id:
            Optional chat session identifier.

        metadata:
            Optional contextual metadata associated with the message.
    """

    user_id: int | str
    message: str
    dataset_id: UUID | None
    session_id: str | None
    metadata: dict[str, Any] | None


@dataclass
class ChatArtifact:
    """
    Represents an optional artifact generated by a chat tool.

    Attributes:
        type:
            Artifact type, such as table or chart.

        content:
            Structured artifact content returned by the chat tool.
    """

    type: str
    content: dict[str, Any]


@dataclass
class ChatMessageResult:
    """
    Represents the workflow execution result.

    Attributes:
        user_id:
            Identifier of the user associated with the processed message.

        session_id:
            Chat session identifier associated with the response, when
            available.

        answer:
            Generated assistant answer.

        intent:
            Intent detected for the processed message.

        tool_used:
            Name of the tool used during processing, when one is selected.

        dataset_id:
            Dataset identifier associated with the request, when available.

        artifact:
            Optional artifact produced during chat processing.
    """

    user_id: int | str
    session_id: str | None
    answer: str
    intent: ChatIntent
    tool_used: str | None
    dataset_id: UUID | None
    artifact: ChatArtifact | None

